type V = string | number | boolean | null | undefined | object;

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
function lit(v: V, cast?: string): string {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v) && cast?.endsWith('[]')) {
    return v.length ? `array[${v.map((x) => q(String(x))).join(',')}]::${cast}` : `'{}'::${cast}`;
  }
  if (typeof v === 'object') return `${q(JSON.stringify(v))}::jsonb`;
  return cast ? `${q(v)}::${cast}` : q(v);
}

function insert(table: string, rows: Record<string, V>[], casts: Record<string, string> = {}): string {
  if (!rows.length) return '';
  const cols = Object.keys(rows[0]!);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c], casts[c])).join(', ')})`).join(',\n');
  return `insert into public.${table} (${cols.join(', ')}) values\n${values}\non conflict do nothing;\n\n`;
}

